"""Единый хелпер экранирования для HTML-сообщений бота.

Все исходящие тексты отправляются с parse_mode="HTML", поэтому любые
динамические данные (имена пользователей, названия питомцев, usernames)
обязаны проходить через esc() — иначе символы <, >, & сломают разметку
или позволят пользователю внедрить свои теги в сообщения чата.
"""
from __future__ import annotations

from html import escape


def esc(value: object) -> str:
    """Экранирует динамическое значение для безопасной вставки в HTML."""
    return escape(str(value if value is not None else ""))
